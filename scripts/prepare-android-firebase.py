from pathlib import Path
import re, shutil, sys
root = Path(__file__).resolve().parents[1]
android = root / 'android'
source = root / 'google-services.json'
if not source.exists():
    print('ERROR: google-services.json is missing from the repository root.')
    sys.exit(1)
app = android / 'app'
app.mkdir(parents=True, exist_ok=True)
shutil.copy2(source, app / 'google-services.json')
# Enable Google services Gradle plugin in the generated Capacitor Android project.
root_gradle = android / 'build.gradle'
if not root_gradle.exists():
    print('ERROR: android/build.gradle was not generated by Capacitor.')
    sys.exit(1)
gradle = root_gradle.read_text()
if 'com.google.gms:google-services' not in gradle:
    match = re.search(r'(dependencies\s*\{)', gradle)
    if not match:
        print('ERROR: Could not locate buildscript dependencies in android/build.gradle.')
        sys.exit(1)
    insert_at = match.end()
    gradle = gradle[:insert_at] + "\n        classpath 'com.google.gms:google-services:4.4.2'" + gradle[insert_at:]
    root_gradle.write_text(gradle)
app_gradle = app / 'build.gradle'
if not app_gradle.exists():
    print('ERROR: android/app/build.gradle was not generated by Capacitor.')
    sys.exit(1)
app_text = app_gradle.read_text()
if 'com.google.gms.google-services' not in app_text:
    app_text += "\n\napply plugin: 'com.google.gms.google-services'\n"
    app_gradle.write_text(app_text)
# Required by the Firebase Authentication plugin's Google Credential Manager integration.
variables = android / 'variables.gradle'
if not variables.exists():
    print('ERROR: android/variables.gradle was not generated by Capacitor.')
    sys.exit(1)
var_text = variables.read_text()
if 'rgcfaIncludeGoogle' not in var_text:
    var_text += "\n\next {\n    rgcfaIncludeGoogle = true\n    androidxCredentialsVersion = '1.3.0'\n}\n"
    variables.write_text(var_text)
print('Android Firebase Google Sign-In Gradle setup applied.')

